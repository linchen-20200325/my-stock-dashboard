# 取數時點守則（2026-08-24 事故後補）
# ══════════════════════════════════════════════════════════════════════
#
# 事故:2026-08-24 08:42 UTC(TW 16:42)手動觸發持股推播,提示層**整行沒印**,
# 但同日 mynews 的歸檔顯示 ^SOX -5.45% / ^IXIC -2.05% —— 遠超過 -1.5% 門檻。
# production log 證實六個標的**全部抓取成功**(NAS proxy 逐一 ✅),
# 也就是說:抓到了,但算出來的變動沒有一個達標。
#
# 兩個都與「拿到哪兩根 K 棒」有關的候選成因:
#   (a) **進行中的 K 棒**:Yahoo 的 interval=1d 在盤中(含盤前)就會為「今天」
#       開一根尚未收盤的棒。若拿它當 last、昨收當 prev,算出來的是
#       「今天到目前為止的變動」≈ 0%,而不是「上一個完整交易日的變動」。
#   (b) **上游給了過期序列**(proxy 快取等)→ 拿到的是好幾天前的兩根。
#
# 兩者的共同點:**沉默地算出一個看起來正常的數字**。故本檔補兩條守則,
# 並在 L1 逐標的 log 出「用了哪兩天、值多少、算出幾 %」——
# 沒有那行 log 正是這次只能靠推論的原因。

US_SESSION_CLOSE_UTC_HOUR = 21
"""美股常規盤收盤的 UTC 保守時點（小時）。

美東收盤 16:00 = **UTC 20:00（夏令 EDT）/ 21:00（冬令 EST）**。取較晚的 21 為保守值:
在 20:00~21:00 UTC 這一小時內（夏令期間）會把當日已收盤的棒也當成進行中而丟掉,
退回用前一個交易日的變動 —— **寧可講昨天的真實變動,也不要講今天的半根棒**。

本專案的排程是 22:30 UTC（TW 06:30），穩穩落在收盤之後，不受此保守值影響；
它保護的是**手動觸發**與未來可能改的時段。"""

LEAD_QUOTE_MAX_AGE_DAYS = 5
"""領先市場報價可接受的最大落後（日曆日）。

超過 → 該標的判為**無法取得**（None），由 L2 顯示「⬜ 未取得」，
**不可**拿過期的兩根棒算出一個看起來正常的變動（§1）。
5 天涵蓋「週五收盤 → 下週一早上」再加一天國定假日的正常情形。"""
