US_SESSION_CLOSE_UTC_HOUR = 21
"""美股常規盤收盤的 UTC 保守時點（小時）。

美東收盤 16:00 = **UTC 20:00（夏令 EDT）/ 21:00（冬令 EST）**。取較晚的 21 為保守值:
在 20:00~21:00 UTC 這一小時內（夏令期間）會把當日已收盤的棒也當成進行中而丟掉,
退回用前一個交易日的變動 —— **寧可講昨天的真實變動,也不要講今天的半根棒**。

本專案的排程是 22:30 UTC（TW 06:30），穩穩落在收盤之後，不受此保守值影響；
它保護的是**手動觸發**與未來可能改的時段。"""

LEAD_QUOTE_MAX_AGE_DAYS = 5
"""領先市場報價可接受的最大落後（日曆日）。

超過 → 該標的判為**無法取得**（None），由 L2 顯示「⬜ 未取得」，
**不可**拿過期的兩根棒算出一個看起來正常的變動（§1）。
5 天涵蓋「週五收盤 → 下週一早上」再加一天國定假日的正常情形。"""


